// Execute production workshop event bindings rather than imitating their mutations.
function bindStudioCard(panel) {
    const start = mangaSource.indexOf("            panelsListEl.querySelectorAll('.mw-panel-card').forEach(card => {");
    const end = mangaSource.indexOf('\n        }\n\n        // Header controls bindings', start);
    assert.ok(start >= 0 && end > start);
    const controls = new Map();
    function control(key, dataset = {}) {
        const element = { dataset, value: '', handlers: {}, addEventListener(type, run) { this.handlers[type] = run; } };
        controls.set(key, element); return element;
    }
    const rows = panel.characters.map((person, index) => {
        const positive = control(`positive-${index}`, { field: 'positive' });
        const id = control(`id-${index}`, { field: 'character_id' });
        const remove = control(`remove-${index}`);
        return { dataset: { person: String(index) }, querySelectorAll: q => q === '[data-field]' ? [positive, id] : [],
            querySelector: q => q === '.rbq-manga-remove-person' ? remove : null };
    });
    const selectors = { '.mw-bubble-text-in': 'text', '.mw-bubble-type-sel': 'type', '.mw-bubble-dir-sel': 'layout',
        '.rbq-manga-non-character': 'non-character', '.mw-panel-dup': 'copy', '.mw-panel-up': 'up', '.mw-panel-down': 'down', '.mw-panel-del': 'delete' };
    Object.values(selectors).forEach(key => control(key));
    const card = { dataset: { idx: '0' }, querySelectorAll: q => q === '.rbq-manga-person' ? rows : [],
        querySelector(q) {
            if (selectors[q]) return controls.get(selectors[q]);
            const match = q.match(/data-person="(\d+)".*data-field="positive"/);
            return match ? controls.get(`positive-${match[1]}`) : null;
        } };
    settings._mangaMode.studio.panels = [panel];
    Object.assign(manga, { studio: settings._mangaMode.studio, panelsListEl: { querySelectorAll: () => [card] },
        store: settings._mangaMode, renderPanelCards() {}, updatePromptPreview() {}, save() {} });
    vm.runInContext(mangaSource.slice(start, end), manga);
    return (key, value, event = key.startsWith('remove-') || ['copy', 'up', 'down', 'delete'].includes(key) ? 'click' :
        key === 'type' || key === 'layout' ? 'change' : 'input') => {
        const element = controls.get(key);
        assert.ok(element?.handlers[event]); element.value = value; element.handlers[event]({ target: element });
    };
}
